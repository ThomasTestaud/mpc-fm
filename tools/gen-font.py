#!/usr/bin/env python3
"""Make launcher/font.h from a PSF console font (printable ASCII only).

Default source: Lat15-Fixed13 from Debian/Ubuntu console-setup, built from
the X11 misc-fixed 6x13 font ("Public domain font. Share and enjoy.").
    python3 tools/gen-font.py /usr/share/consolefonts/Lat15-Fixed13.psf.gz > launcher/font.h
With a second argument, the names get that prefix (several fonts in one file):
    (python3 tools/gen-font.py .../Lat15-Fixed13.psf.gz font13
     python3 tools/gen-font.py .../Lat15-Fixed18.psf.gz font18) > src/ui/fonts.h
"""
import gzip, struct, sys

def load_psf(path):
    data = gzip.open(path).read() if path.endswith('.gz') else open(path, 'rb').read()
    if data[:2] == b'\x36\x04':                      # PSF1
        mode, h = data[2], data[3]
        n = 512 if mode & 1 else 256
        return 8, h, [data[4 + i * h: 4 + (i + 1) * h] for i in range(n)], None
    if data[:4] == b'\x72\xb5\x4a\x86':              # PSF2
        _, _, hsize, flags, n, size, h, w = struct.unpack('<8I', data[:32])
        glyphs = [data[hsize + i * size: hsize + (i + 1) * size] for i in range(n)]
        uni = None
        if flags & 1:                                 # unicode table: char -> glyph index
            uni, pos = {}, hsize + n * size
            for g in range(n):
                while pos < len(data) and data[pos] != 0xff:
                    if data[pos] == 0xfe:            # sequences: skip to the end marker
                        while data[pos] != 0xff: pos += 1
                        break
                    l = 1 if data[pos] < 0x80 else 2 if data[pos] < 0xe0 else 3 if data[pos] < 0xf0 else 4
                    ch = data[pos:pos + l].decode('utf-8', 'replace'); pos += l
                    uni.setdefault(ch, g)
                pos += 1
        return w, h, glyphs, uni
    sys.exit('not a PSF font')

w, h, glyphs, uni = load_psf(sys.argv[1])
rowbytes = (w + 7) // 8
used = 0
for c in range(32, 127):                              # real width: rightmost lit column
    g = glyphs[uni[chr(c)] if uni and chr(c) in uni else c]
    for r in range(h):
        bits = int.from_bytes(g[r * rowbytes:(r + 1) * rowbytes], 'big')
        for x in range(w):
            if bits & (1 << (rowbytes * 8 - 1 - x)): used = max(used, x + 1)
cw = max(used, 5)
pre = sys.argv[2] if len(sys.argv) > 2 else None
W, H, ROWS = (pre.upper() + '_W', pre.upper() + '_H', pre + '_rows') if pre else ('FONT_W', 'FONT_H', 'font_rows')
print('/* Generated by tools/gen-font.py from %s.' % sys.argv[1].split('/')[-1])
print(' * X11 misc-fixed via console-setup: public domain. Printable ASCII.')
print(' * One byte per row, bit 7 = leftmost pixel. */')
if pre:
    print('#define %s %d\n#define %s %d' % (W, cw, H, h))
    print('static const unsigned char %s[127 - 32][%s] = {' % (ROWS, H))
else:
    print('#define FONT_W %d\n#define FONT_H %d\n#define FONT_FIRST 32\n#define FONT_LAST 126' % (cw, h))
    print('static const unsigned char font_rows[FONT_LAST - FONT_FIRST + 1][FONT_H] = {')
for c in range(32, 127):
    g = glyphs[uni[chr(c)] if uni and chr(c) in uni else c]
    rows = [g[r * rowbytes] for r in range(h)]
    print('    {%s}, /* %r */' % (', '.join('0x%02x' % b for b in rows), chr(c)))
print('};')
